import assert from 'node:assert/strict';
import { readAssistantDraft, writeAssistantDraft, planDraftValues } from '../src/lighthouseDrafts.ts';
const rows = new Map<string, string>();
const storage = { getItem: (key: string) => rows.get(key) ?? null, setItem: (key: string, value: string) => { rows.set(key, value); }, removeItem: (key: string) => { rows.delete(key); } } as Storage;
const plan = { id: 'plan-A', version: 2, status: 'needs_input', fields: [{ name: 'name' }, { name: 'file' }] };
const value = { conversation: 'conversation-A', at: Date.now(), text: '尚未发送', commands: [], files: [], plans: { 'plan-A': { version: 2, values: { name: '未保存的通告', file: ['uploaded-ref'] }, files: [{ id: 'uploaded-ref', name: '证明.jpg' }] } } };
assert.ok(writeAssistantDraft(storage, 'account-A', value));
const restored = readAssistantDraft(storage, 'account-A', 'conversation-A');
assert.equal(restored?.text, '尚未发送');
assert.deepEqual(planDraftValues(restored, plan), value.plans['plan-A'].values);
assert.equal(readAssistantDraft(storage, 'account-B', 'conversation-A'), null);
assert.equal(readAssistantDraft(storage, 'account-A', 'conversation-B'), null);
assert.equal(readAssistantDraft(storage, 'account-A', 'conversation-A', value.at + 8 * 86400000), null);
assert.equal(planDraftValues(restored, { ...plan, version: 3 }), null);
assert.equal(planDraftValues(restored, { ...plan, status: 'completed' }), null);
assert.ok(writeAssistantDraft(storage, 'account-A', { ...value, plans: { ...value.plans, secret: { version: 1, values: { api_key: 'never-store', password: 'never-store', name: 'retained' }, files: [] } } }));
assert.ok(![...rows.values()][0].includes('never-store'));
assert.equal(writeAssistantDraft(storage, 'account-A', { ...value, text: 'x'.repeat(1024 * 1024) }), false);
assert.equal(writeAssistantDraft({ ...storage, setItem: () => { throw new Error('quota'); } }, 'account-A', value), false);
assert.ok(writeAssistantDraft(storage, 'account-A', { ...value, text: '', plans: {} }));
assert.equal(rows.size, 0);
rows.set('lighthouse_draft:account-A', '{bad json');
assert.equal(readAssistantDraft(storage, 'account-A', 'conversation-A'), null);
console.log('[LighthouseDraftCheck] OK');
