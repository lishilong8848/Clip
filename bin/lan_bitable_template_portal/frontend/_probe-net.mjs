import path from 'node:path';import {preview} from 'vite';import {chromium} from 'playwright';
const root=process.cwd();
const s=await preview({root,configFile:path.join(root,'vite.workspace-v2.config.ts'),logLevel:'error',preview:{host:'127.0.0.1',port:0,proxy:{}}});
const origin='http://127.0.0.1:'+s.httpServer.address().port;
const b=await chromium.launch({headless:true});const c=await b.newContext({viewport:{width:1440,height:950}});
await c.route('**/*',async r=>{const q=r.request(),u=new URL(q.url());if(u.origin!==origin)return r.abort();
 if(!u.pathname.startsWith('/api/'))return r.continue();
 if(u.pathname==='/api/auth/status')return r.fulfill({status:200,contentType:'application/json',body:JSON.stringify({ok:true,authenticated:true,user:{open_id:'self',name:'隔离验收主管',level:'L1',category:'manager',modules:['accounts'],can_manage_accounts:true,scopes:[{value:'A',label:'A楼'}]}})});
 return r.fulfill({status:200,contentType:'application/json',body:'{"ok":true,"items":[],"records":[],"users":[],"settings":{}}'});});
const p=await c.newPage();
p.on('request',q=>{if(!q.url().endsWith('.png'))console.log('REQ',q.method(),new URL(q.url()).pathname+new URL(q.url()).search);});
p.on('response',r=>{if(!/\.png|vnet/.test(r.url()))console.log('RES',r.status(),new URL(r.url()).pathname);});
p.on('requestfailed',r=>console.log('FAIL',new URL(r.url()).pathname,r.failure()?.errorText));
p.on('console',m=>{if(m.type()==='error')console.log('CONSOLE',m.text().slice(0,200));});
p.on('pageerror',e=>console.log('PAGEERR',e.message.slice(0,200)));
await p.goto(origin+'/assets/workspace-v2/index.html?__page=/admin/settings');
await p.waitForTimeout(4000);
console.log('status text:',await p.locator('#entry-status').textContent().catch(()=>'-'));
await b.close();await s.close();
